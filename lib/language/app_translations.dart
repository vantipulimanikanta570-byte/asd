  String text(String key) {
    Map<String, String> selected;

    if (language == 'తెలుగు') {
      selected = telugu;
    } else if (language == 'हिंदी') {
      selected = hindi;
    } else {
      selected = english;
    }

    return selected[key] ??
        english[key] ??
        key;
  }
